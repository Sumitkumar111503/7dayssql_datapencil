Q1. Total Sales Value
Calculate the total sales value from non-cancelled orders.
select 
      sum( order_items.quantity * order_items.unit_price) as total_sales
      from order_items 
      join orders 
      on order_items.order_id = orders.order_id 
      where orders.status != 'cancelled' ;
      

Q2. Sales by Product Category
Identify which product categories generate the most sales.
 select 
	products.category,
      sum( order_items.quantity * order_items.unit_price) as total_revenue
      from order_items 
      join orders 
      on order_items.order_id = orders.order_id 
      join products
      on order_items.product_id = products.product_id
      where orders.status != 'cancelled'
      group by products.category
      order by total_revenue desc ;
      

Q3. Top 10 Products by Sales Value
Find the 10 products generating the most sales value.
select 
	products.product_name,
      sum( order_items.quantity * order_items.unit_price) as total_revenue
      from order_items 
      join orders 
      on order_items.order_id = orders.order_id 
      join products
      on order_items.product_id = products.product_id
      where orders.status != 'cancelled'
      group by products.product_name
      order by total_revenue desc 
      limit 10;
      
      
Q4. Total Quantity Sold by Product

Calculate the total quantity sold for each product.

select 
      products.product_name,
      count(order_items.quantity) as qauntity_sales
      from order_items
      join products
      on order_items.product_id = products.product_id
      group by  products.product_name
      order by qauntity_sales desc;
      

Q5. Average Selling Price by Category
Calculate the average product selling price in each category.
select  
      category,
      avg(price)
      from products
      group by  category;
      

