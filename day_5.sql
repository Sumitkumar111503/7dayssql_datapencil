Q7. Estimated Product Profit
-Calculate estimated profit by product using the 
--product cost and item selling price.
select
      products.product_id,
      products.product_name,
      sum(order_items.quantity*(products.price - products.cost )) as estenmated_profit
      from products
      join order_items
      on products.product_id = order_items.product_id
      join orders
      on orders.order_id = order_items.order_id
      where orders.status != 'cancelled'
      group by  products.product_id,
                 products.product_name ;
                 

Q8. Top 5 Categories by Quantity Sold
Find the five categories with the highest total quantity sold.
